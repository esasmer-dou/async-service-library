package com.reactor.asl.spring.boot;

import org.apache.commons.logging.Log;
import org.apache.commons.logging.LogFactory;
import org.springframework.beans.factory.BeanFactory;
import org.springframework.beans.factory.BeanFactoryAware;
import org.springframework.beans.factory.ListableBeanFactory;
import org.springframework.beans.factory.SmartInitializingSingleton;
import org.springframework.util.ClassUtils;

import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.Objects;
import java.util.Optional;
import java.util.TreeMap;

/**
 * Detects governed interfaces whose implementation is a bean but whose generated ASL wrapper is not.
 *
 * <p>Spring auto-wrapping is generated by the annotation processor only when the governed interface
 * and its {@code @Service}/{@code @Component} implementation are compiled together. In a
 * multi-module build (API module + implementation module) nothing is generated and callers silently
 * receive the raw implementation, bypassing every runtime control. This check makes that visible.</p>
 */
final class AslGovernedBeanVerifier implements SmartInitializingSingleton, BeanFactoryAware {
    static final String WRAPPER_SUFFIX = "AslGoverned";
    private static final Log log = LogFactory.getLog(AslGovernedBeanVerifier.class);

    private final UnwrappedGovernedBeanPolicy policy;
    private ListableBeanFactory beanFactory;

    AslGovernedBeanVerifier(UnwrappedGovernedBeanPolicy policy) {
        this.policy = Objects.requireNonNull(policy, "policy");
    }

    @Override
    public void setBeanFactory(BeanFactory beanFactory) {
        this.beanFactory = beanFactory instanceof ListableBeanFactory listable ? listable : null;
    }

    @Override
    public void afterSingletonsInstantiated() {
        if (policy == UnwrappedGovernedBeanPolicy.IGNORE || beanFactory == null) {
            return;
        }
        Map<String, List<String>> violations = findUnwrapped(beanFactory);
        if (violations.isEmpty()) {
            return;
        }
        String message = describe(violations);
        if (policy == UnwrappedGovernedBeanPolicy.FAIL) {
            throw new IllegalStateException(message);
        }
        log.warn(message);
    }

    static Map<String, List<String>> findUnwrapped(ListableBeanFactory beanFactory) {
        Map<Class<?>, Optional<Class<?>>> wrapperCache = new HashMap<>();
        Map<Class<?>, List<String>> implementationsByInterface = new HashMap<>();
        Map<Class<?>, Boolean> wrapped = new HashMap<>();

        java.util.Set<String> beanNames = new java.util.LinkedHashSet<>(List.of(beanFactory.getBeanDefinitionNames()));
        // Also include manually registered singletons, which have no bean definition.
        beanNames.addAll(List.of(beanFactory.getBeanNamesForType(Object.class, true, false)));
        for (String beanName : beanNames) {
            Class<?> beanType;
            try {
                beanType = beanFactory.getType(beanName, false);
            } catch (RuntimeException unresolvable) {
                continue;
            }
            if (beanType == null) {
                continue;
            }
            for (Class<?> candidate : ClassUtils.getAllInterfacesForClassAsSet(beanType)) {
                if (isFrameworkType(candidate)) {
                    continue;
                }
                Optional<Class<?>> wrapper = wrapperCache.computeIfAbsent(candidate, AslGovernedBeanVerifier::wrapperFor);
                if (wrapper.isEmpty()) {
                    continue;
                }
                if (wrapper.get().isAssignableFrom(beanType)) {
                    wrapped.put(candidate, true);
                } else {
                    implementationsByInterface.computeIfAbsent(candidate, ignored -> new ArrayList<>()).add(beanName);
                }
            }
        }

        Map<String, List<String>> violations = new TreeMap<>();
        implementationsByInterface.forEach((governedInterface, beans) -> {
            if (!wrapped.getOrDefault(governedInterface, false)) {
                violations.put(governedInterface.getName(), List.copyOf(beans));
            }
        });
        return violations;
    }

    private static Optional<Class<?>> wrapperFor(Class<?> candidate) {
        try {
            Class<?> wrapper = ClassUtils.forName(wrapperClassName(candidate), candidate.getClassLoader());
            return candidate.isAssignableFrom(wrapper) ? Optional.of(wrapper) : Optional.empty();
        } catch (ClassNotFoundException | LinkageError notGoverned) {
            return Optional.empty();
        }
    }

    /** Mirrors the processor naming: nested {@code Outer.Inner} becomes {@code Outer_InnerAslGoverned}. */
    static String wrapperClassName(Class<?> governedInterface) {
        String packageName = governedInterface.getPackageName();
        String binaryName = governedInterface.getName();
        String nestedName = packageName.isEmpty() ? binaryName : binaryName.substring(packageName.length() + 1);
        String flattened = nestedName.replace('$', '_') + WRAPPER_SUFFIX;
        return packageName.isEmpty() ? flattened : packageName + "." + flattened;
    }

    private static boolean isFrameworkType(Class<?> type) {
        String name = type.getName();
        return name.startsWith("java.") || name.startsWith("javax.") || name.startsWith("jakarta.")
                || name.startsWith("org.springframework.") || name.startsWith("com.reactor.asl.core.");
    }

    private static String describe(Map<String, List<String>> violations) {
        StringBuilder message = new StringBuilder(
                "ASL governed interfaces are exposed without their governed wrapper; callers bypass runtime controls: ");
        violations.forEach((governedInterface, beans) -> message
                .append(governedInterface).append(" (beans ").append(beans).append("); "));
        message.append("Compile the implementation together with the governed interface so the processor ")
                .append("generates the Spring configuration, or declare a bean that returns <Interface>Asl.wrap(impl, registry). ")
                .append("Set asl.runtime.unwrapped-governed-bean-policy to FAIL to enforce, or IGNORE to silence.");
        return message.toString();
    }
}
